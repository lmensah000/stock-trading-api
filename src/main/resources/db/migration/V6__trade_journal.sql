-- ============================================================
--  V6 — trade journal, annotations and the stated rule book
--
--  Records what was actually traded, what the market looked like at that
--  instant, and the chart that was marked up. The purpose is to learn the rules
--  that are traded but never written down, by comparing behaviour against the
--  rules that are written down.
--
--  Three design points worth keeping:
--
--  1. context_fidelity is a column, not an assumption. An imported fill has no
--     option chain from the moment it filled - historical chains with open
--     interest are not freely available - while a live-captured one does.
--     Fitting across both tiers as if they were the same observation would
--     weight the thin records equally with the rich ones, so every analysis is
--     scoped to one tier.
--
--  2. judgement is separate from r_multiple, deliberately. A winning trade can
--     be a bad decision and a loser can be a good one; fitting to P&L teaches
--     the system to chase luck. The outcome and the trader's own verdict are
--     two different facts and are never collapsed into one label.
--
--  3. expiry is a DATE. trading/model/Options stores its expiration as a
--     VARCHAR, which is a known defect - this table does not copy it, because
--     expiry arithmetic on strings is how an option looks unexpired forever.
-- ============================================================
CREATE TABLE journal_entries (
    id                BIGINT AUTO_INCREMENT PRIMARY KEY,
    user_id           BIGINT NOT NULL,

    underlying        VARCHAR(16) NOT NULL,

    -- OPTION or EQUITY. Options are the point, but an equity fill alongside
    -- them is still evidence about the same judgement.
    instrument        VARCHAR(8) NOT NULL DEFAULT 'OPTION',

    -- Null for an equity fill.
    option_type       VARCHAR(8) NULL,
    strike            DECIMAL(19,4) NULL,
    expiry            DATE NULL,

    side              VARCHAR(8) NOT NULL,
    quantity          DECIMAL(19,4) NOT NULL,
    fill_price        DECIMAL(19,4) NOT NULL,
    filled_at         TIMESTAMP(6) NOT NULL,

    -- BROKER_IMPORT or LIVE_CAPTURE.
    source            VARCHAR(24) NOT NULL,

    -- UNDERLYING_ONLY, UNDERLYING_PLUS_EOD_CHAIN, FULL_CHAIN_AT_FILL.
    context_fidelity  VARCHAR(32) NOT NULL,

    -- The market as it stood at the fill, as JSON: bars per timeframe, the
    -- previous close, the chain row when available, computed indicators. Shaped
    -- so an EvaluationContext can be rebuilt from it and the real rules
    -- replayed against it.
    snapshot_json     LONGTEXT NULL,

    -- An exit points at the entry it closes, so an outcome is attributable.
    closes_entry_id   BIGINT NULL,

    -- Set when the round trip closes. Outcome only; see design point 2.
    r_multiple        DECIMAL(19,4) NULL,

    -- WOULD_REPEAT, WOULD_NOT_REPEAT, UNSURE. The trader's own verdict.
    judgement         VARCHAR(24) NULL,
    judged_at         TIMESTAMP(6) NULL,

    notes             VARCHAR(1024) NULL,

    -- The broker's own fill identifier. Carries the uniqueness below, so
    -- re-running an import is a no-op rather than a way to double-count a
    -- trade - which would corrupt every statistic computed from this table.
    external_id       VARCHAR(128) NULL,

    created_at        TIMESTAMP(6) NOT NULL,
    updated_at        TIMESTAMP(6) NOT NULL,

    KEY idx_journal_user_filled (user_id, filled_at),
    KEY idx_journal_underlying (user_id, underlying),
    KEY idx_journal_fidelity (user_id, context_fidelity),

    CONSTRAINT uq_journal_external UNIQUE (user_id, external_id),

    CONSTRAINT fk_journal_user
        FOREIGN KEY (user_id) REFERENCES users(id)
        ON DELETE CASCADE ON UPDATE CASCADE,

    -- Self-reference, so deleting an entry cannot orphan the exit that closed
    -- it with a dangling pointer.
    CONSTRAINT fk_journal_closes
        FOREIGN KEY (closes_entry_id) REFERENCES journal_entries(id)
        ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ============================================================
--  ANNOTATIONS
--
--  Marked-up chart screenshots. The bytes live on disk and this table holds the
--  reference: an image per trade would otherwise be carried by every database
--  backup, for data that is write-once and read rarely.
--
--  original_filename is recorded but never used to build a path. A
--  client-supplied name is untrusted input and is the standard route to writing
--  outside the intended directory.
-- ============================================================
CREATE TABLE journal_annotations (
    id                BIGINT AUTO_INCREMENT PRIMARY KEY,
    journal_entry_id  BIGINT NOT NULL,

    -- Relative to the configured annotation directory, and generated by the
    -- server.
    stored_path       VARCHAR(512) NOT NULL,

    -- Determined from the file's magic bytes, not from what the client claimed.
    content_type      VARCHAR(64) NOT NULL,
    byte_size         BIGINT NOT NULL,
    sha256            CHAR(64) NOT NULL,

    original_filename VARCHAR(255) NULL,
    caption           VARCHAR(512) NULL,
    uploaded_at       TIMESTAMP(6) NOT NULL,

    -- The same image attached twice is one annotation, not two.
    CONSTRAINT uq_annotation_entry_hash UNIQUE (journal_entry_id, sha256),

    CONSTRAINT fk_annotation_entry
        FOREIGN KEY (journal_entry_id) REFERENCES journal_entries(id)
        ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ============================================================
--  STATED RULES
--
--  Rules the trader believes they follow. Their value is not that the system
--  obeys them - it is the contradiction between them and the fills recorded
--  above. "You said never below the 21 EMA; 40% of your fills were below it"
--  is often where someone finds the rule they actually trade.
-- ============================================================
CREATE TABLE journal_rules (
    id           BIGINT AUTO_INCREMENT PRIMARY KEY,
    user_id      BIGINT NOT NULL,

    -- Plain English, as stated.
    statement    VARCHAR(512) NOT NULL,

    -- A checkable predicate over a snapshot's features, in the small
    -- constrained form the rule book understands.
    expression   VARCHAR(512) NOT NULL,

    active       TINYINT NOT NULL DEFAULT 1,
    created_at   TIMESTAMP(6) NOT NULL,

    KEY idx_journal_rules_user (user_id, active),

    CONSTRAINT fk_journal_rules_user
        FOREIGN KEY (user_id) REFERENCES users(id)
        ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
